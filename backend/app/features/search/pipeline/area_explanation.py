"""AI-generated explanations for ranked areas.

Mirrors the structure of ``intent_parser.py``.  When
``settings.USE_AI_AREA_EXPLANATIONS`` is True this stage calls Gemini to
produce personalised “why this area” copy for each candidate.  When False
(or when the API key is missing) the caller should fall back to the
heuristic reasons generated by ``rank_for_intent``.
"""

from __future__ import annotations

import json

from app.core import llm
from app.core.config import settings
from app.core.logging import get_pipeline_logger

log = get_pipeline_logger("search.area_explanation")

_SYSTEM_PROMPT = """You are a real-estate investment advisor for ESTRA Glimmora.

Given a user's search intent and a ranked list of micro-markets, write a
structured investment brief for EACH area covering all 4 points below.

Return ONLY a JSON array. No prose, no markdown fences.

Schema per area:
[
  {
    "area_name": string,
    "why_it_matches": string,      // why this area matches the user's search intent (budget, BHK, ROI target, etc.)
    "recent_change": string,       // what changed recently: infrastructure, policy, demand shift, new projects
    "attraction": string,          // what makes this area attractive as an investment (trends, yield, connectivity, etc.)
    "projected_movement": string   // where prices/rental are headed in the next 1-3 years
  },
  ...
]

Tone: confident but honest. Mention specific numbers when available (yield %,
price trend %, PSF values). Keep each field concise (under 150 characters)."""


def run(
    query: str,
    areas: list[dict],
) -> list[dict[str, str]] | None:
    """Generate AI explanations for a list of ranked areas.

    Returns ``None`` when the feature is disabled, Vertex isn't configured,
    or the LLM call fails. Callers should fall back to template reasons.
    """
    if not settings.USE_AI_AREA_EXPLANATIONS:
        return None
    if not areas:
        return None
    if not llm.is_available():
        return None

    payload = {"user_query": query, "areas": areas}
    text = llm.generate_content(
        system_instruction=_SYSTEM_PROMPT,
        user_prompt=json.dumps(payload, ensure_ascii=False),
        temperature=0.3,
    )
    if not text:
        log.warning("Vertex returned empty area-explanation response")
        return None

    try:
        parsed = json.loads(text)
    except json.JSONDecodeError:
        log.warning("Vertex returned non-JSON area explanation: %r", text[:200])
        return None

    if not isinstance(parsed, list):
        log.warning("Vertex area explanation was not a JSON array: %r", type(parsed).__name__)
        return None

    # Normalize each item to guarantee the expected keys
    result = []
    for item in parsed:
        if isinstance(item, dict) and "area_name" in item:
            result.append(
                {
                    "area_name": item["area_name"],
                    "why_it_matches": item.get("why_it_matches", ""),
                    "recent_change": item.get("recent_change", ""),
                    "attraction": item.get("attraction", ""),
                    "projected_movement": item.get("projected_movement", ""),
                }
            )

    if len(result) != len(areas):
        log.warning(
            "area explanation count mismatch: expected %d, got %d",
            len(areas),
            len(result),
        )

    return result
