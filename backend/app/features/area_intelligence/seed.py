"""Hydrate micro_markets + displayable property_listings from seed files.

Runs on every boot from ``app.main.lifespan`` so teammates can clone the
repo and get a working area-intelligence API without running the scraper
or ingestion workers.

Idempotent: skips if ``micro_markets`` already has rows.

Seed files live at ``backend/data/seed/`` and are regenerated by
``python -m app.workers.export_seed`` after a fresh ingest.
"""

from __future__ import annotations

import csv
import json
from datetime import datetime
from pathlib import Path
from typing import Any

from app.core.database import SessionLocal
from app.core.logging import get_logger
from app.features.area_intelligence.models import MicroMarket
from app.features.property_intelligence.models import PropertyListing

log = get_logger("features.area_intelligence.seed")

SEED_DIR = Path(__file__).resolve().parents[3] / "data" / "seed"
MICRO_MARKETS_FILE = SEED_DIR / "micro_markets.json"
PROPERTY_LISTINGS_FILE = SEED_DIR / "property_listings.csv"

_DATETIME_COLUMNS_MM = {"last_scraped_at", "created_at"}
_DATETIME_COLUMNS_PL = {"scraped_at", "last_seen_at"}
_INT_COLUMNS_PL = {"bedrooms", "bathrooms"}
_FLOAT_COLUMNS_PL = {"area_sqft", "price_inr", "price_per_sqft"}


def _parse_dt(value: Any) -> datetime | None:
    if value in (None, "", "None"):
        return None
    if isinstance(value, datetime):
        return value
    return datetime.fromisoformat(str(value))


def _csv_to_typed(row: dict[str, str]) -> dict[str, Any]:
    """Coerce CSV string values back to the types PropertyListing expects."""
    out: dict[str, Any] = {}
    for key, raw in row.items():
        if raw == "" or raw is None:
            out[key] = None
            continue
        if key in _DATETIME_COLUMNS_PL:
            out[key] = _parse_dt(raw)
        elif key in _INT_COLUMNS_PL:
            out[key] = int(float(raw))
        elif key in _FLOAT_COLUMNS_PL:
            out[key] = float(raw)
        else:
            out[key] = raw
    return out


def seed_area_intelligence() -> None:
    db = SessionLocal()
    try:
        if db.query(MicroMarket).count() > 0:
            return

        if not MICRO_MARKETS_FILE.exists():
            log.warning("seed file missing: %s — skipping hydrate", MICRO_MARKETS_FILE)
            return

        market_rows = json.loads(MICRO_MARKETS_FILE.read_text(encoding="utf-8"))
        for row in market_rows:
            for col in _DATETIME_COLUMNS_MM:
                if col in row:
                    row[col] = _parse_dt(row[col])
            db.add(MicroMarket(**row))
        log.info("seeded %d micro_markets from %s", len(market_rows), MICRO_MARKETS_FILE)

        if PROPERTY_LISTINGS_FILE.exists():
            with PROPERTY_LISTINGS_FILE.open("r", encoding="utf-8", newline="") as f:
                reader = csv.DictReader(f)
                count = 0
                for raw_row in reader:
                    db.add(PropertyListing(**_csv_to_typed(raw_row)))
                    count += 1
            log.info(
                "seeded %d property_listings from %s", count, PROPERTY_LISTINGS_FILE
            )
        else:
            log.warning(
                "property listings seed missing: %s — micro_markets only",
                PROPERTY_LISTINGS_FILE,
            )

        db.commit()
    finally:
        db.close()
